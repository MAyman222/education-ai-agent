const assert=require('node:assert/strict');
const flow=require('./flow.js');
const control=checked=>({checked,getAttribute:()=>null});
const question=(key,score,checked=false)=>({key,score,controls:[control(checked)],field:null});
const completed=new Set();
const q1=question('first',0),q2=question('second',150),q3=question('third',250);
assert.equal(flow.next([q1,q2,q3],completed).key,'first');
q1.controls[0].checked=true;
assert.equal(flow.next([q1,q2,q3],completed).key,'second');
completed.add('second');
assert.equal(flow.next([q1,q2,q3],completed).key,'third');
assert.equal(flow.next([q1,q2,q3],completed,new Set(['third']),true),null);
assert.equal(flow.next([q1,q2,q3],completed,new Set(['third']),false).key,'third');
const field={key:'written',score:0,controls:[],field:{value:'Already answered'}};
assert.equal(flow.next([field,q3],completed).key,'third');
const aria={key:'aria',score:0,controls:[{getAttribute:()=> 'true'}],field:null};
assert.equal(flow.next([aria,q3],completed).key,'third');
assert.equal(flow.next([],completed),null);
console.log('PASS: 8 question progression regressions (first, next, completed, automatic retry, manual retry, filled field, ARIA selection, empty page).');
